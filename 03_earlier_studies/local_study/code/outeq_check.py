"""Output-equivalence execution of the feedback fixes (PREREGISTRATION
Amendment 5, Section A5.3; locked 2026-11-06 12:15 UTC).

The feedback study (code/feedback.py, PREREGISTRATION Section 5) claims
deterministic-rewriter fixes repair failing pipelines, but revised loads
were computed ANALYTICALLY (Amendment 2) and outputs were never compared.
This study executes the ORIGINAL and REPAIRED SQL of each fixable
pipeline in DuckDB and compares the output relations EXACTLY (identical
key sets; identical COUNT and SUM on every key; 0 mismatched keys; no
tolerance).

Checked subset (pre-registered feasible set):
- EQ1M corpora (n_fact=1,000,000, n_fact2=600,000; families
  {zipf, lognormal, mixed} x seeds {101, 202}, generated by the
  UNMODIFIED code/gen_dataset.py): G_A, G_N, W_A (salting, 16 salts),
  J_A, J_B, J_N (pre-aggregation before the join).
- EQ200K corpora (n_fact=200,000, n_fact2=120,000; same families x
  seeds): F_A, F_B (pre-aggregation of both facts before the join).

Fix types: J_* and F_* = pre-aggregation before the join; G_A / G_N /
W_A = salting with 16 salts. kN's NULL group is stored as the int32
sentinel -1 in the parquet (not SQL NULL); grouping is on the raw
column, so the -1 group is an ordinary group for G_N and is filtered
by the join (no dim key -1) on both sides for J_N.

Execution envelope (pre-registered): DuckDB threads=2,
memory_limit='2GB', per-query wall-clock cap 900 s. Each
(dataset, pipeline, side) query runs as a separate subprocess
invocation of code/outeq_runner.py under a 900 s timeout; a query
exceeding the envelope is recorded INFEASIBLE with its reason and is
NOT retried under weaker settings.

Per instance the driver also records the original pipeline's
ground-truth verdict AT THE CHECK SCALE, computed from the corpus
counts.npz via code/common.py loads_from_counts + verdict
(T_load = 0.02 * n_fact).

Outputs: results/outeq/summary.json and results/outeq/README.md.
No existing file is modified.
"""
import json, os, subprocess, sys, tempfile, time
from datetime import datetime, timezone

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import K, loads_from_counts, verdict  # noqa: E402

BASE = os.path.expanduser("~/workspace/blind-at-scale")
CODE = os.path.join(BASE, "code")
DATA = os.path.join(BASE, "data")
OUTDIR = os.path.join(BASE, "results", "outeq")
RUNNER = os.path.join(CODE, "outeq_runner.py")
TIMEOUT_S = 900

FAMILIES = ("zipf", "lognormal", "mixed")
SEEDS = (101, 202)

# (pipeline, key column, fix kind); fix kind in {"salt", "join", "ff"}
EQ1M_PIPELINES = [
    ("G_A", "kA", "salt"),
    ("G_N", "kN", "salt"),
    ("W_A", "kA", "salt"),
    ("J_A", "kA", "join"),
    ("J_B", "kB", "join"),
    ("J_N", "kN", "join"),
]
EQ200K_PIPELINES = [
    ("F_A", "kA", "ff"),
    ("F_B", "kB", "ff"),
]


def sql_pair(kind, col):
    """(original_sql, repaired_sql) with the actual key column substituted."""
    if kind == "salt":
        orig = (f"SELECT {col} AS key, COUNT(*) AS c, "
                f"CAST(SUM(s) AS BIGINT) AS ss FROM fact GROUP BY {col}")
        rep = (f"SELECT key, CAST(SUM(c) AS BIGINT) AS c, "
               f"CAST(SUM(ss) AS BIGINT) AS ss FROM "
               f"(SELECT {col} AS key, s % 16 AS salt, COUNT(*) AS c, "
               f"CAST(SUM(s) AS BIGINT) AS ss FROM fact "
               f"GROUP BY {col}, s % 16) GROUP BY key")
    elif kind == "join":
        orig = (f"SELECT f.{col} AS key, COUNT(*) AS c, "
                f"CAST(SUM(f.s) AS BIGINT) AS ss FROM fact f "
                f"JOIN dim d ON f.{col} = d.dim_key GROUP BY f.{col}")
        rep = (f"SELECT p.key AS key, p.c AS c, p.ss AS ss FROM "
               f"(SELECT {col} AS key, COUNT(*) AS c, "
               f"CAST(SUM(s) AS BIGINT) AS ss FROM fact GROUP BY {col}) p "
               f"JOIN dim d ON p.key = d.dim_key")
    elif kind == "ff":
        orig = (f"SELECT f1.{col} AS key, COUNT(*) AS c, "
                f"CAST(SUM(f1.s) AS BIGINT) AS ss FROM fact f1 "
                f"JOIN fact2 f2 ON f1.{col} = f2.{col} GROUP BY f1.{col}")
        rep = (f"SELECT a.key AS key, a.c1 * b.c2 AS c, a.ss1 * b.c2 AS ss "
               f"FROM (SELECT {col} AS key, COUNT(*) AS c1, "
               f"CAST(SUM(s) AS BIGINT) AS ss1 FROM fact GROUP BY {col}) a "
               f"JOIN (SELECT {col} AS key, COUNT(*) AS c2 FROM fact2 "
               f"GROUP BY {col}) b ON a.key = b.key")
    else:
        raise ValueError(kind)
    return orig, rep


def gt_verdict_at_check_scale(corpus_dir, pid, n_fact):
    z = np.load(os.path.join(corpus_dir, "counts.npz"))
    counts = {k: z[k] for k in z.files}
    fact = {c: counts[f"fact_{c}"] for c in ("kA", "kB", "kC", "kN")}
    fact2 = {c: counts[f"fact2_{c}"] for c in ("kA", "kB")}
    loads = loads_from_counts(fact, fact2, float(counts["null_count"]),
                              np.ones(K, dtype=bool),
                              distinct_counts=counts["distinct_A"],
                              n_fact=n_fact)
    return verdict(loads[pid], pid, n_fact), float(loads[pid])


def run_one_query(corpus_dir, sql, out_path):
    """Run one query in a subprocess under the 900 s cap.

    Returns (status, wall_s, reason): status in {"OK", "INFEASIBLE"}.
    """
    cmd = [sys.executable, RUNNER,
           "--fact", os.path.join(corpus_dir, "fact.parquet"),
           "--fact2", os.path.join(corpus_dir, "fact2.parquet"),
           "--dim", os.path.join(corpus_dir, "dim.parquet"),
           "--sql", sql, "--out", out_path]
    t0 = time.perf_counter()
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True,
                              timeout=TIMEOUT_S)
    except subprocess.TimeoutExpired:
        return ("INFEASIBLE", float(TIMEOUT_S),
                f"exceeded per-query wall-clock cap of {TIMEOUT_S} s "
                f"(subprocess timeout; killed, not retried)")
    wall_driver = time.perf_counter() - t0
    if proc.returncode != 0:
        tail = (proc.stderr or "").strip().splitlines()
        reason = ("runner exited %d: %s"
                  % (proc.returncode, tail[-1] if tail else "(no stderr)"))
        return "INFEASIBLE", wall_driver, reason
    try:
        info = json.loads(proc.stdout.strip().splitlines()[-1])
        return "OK", float(info["wall_s"]), None
    except Exception:
        return "OK", wall_driver, None


def _read_result(path):
    """Read a runner result parquet via DuckDB (the venv has no pyarrow;
    DuckDB reads parquet natively and .df() needs no extra engine)."""
    import duckdb
    con = duckdb.connect()
    df = con.execute(
        f"SELECT * FROM '{path}' ORDER BY key").df()
    con.close()
    return df


def compare(orig_path, rep_path):
    """Exact comparison of two result relations (columns key, c, ss)."""
    a = _read_result(orig_path).reset_index(drop=True)
    b = _read_result(rep_path).reset_index(drop=True)
    for df in (a, b):
        df["key"] = df["key"].astype(np.int64)
        df["c"] = df["c"].astype(np.int64)
        df["ss"] = df["ss"].astype(np.int64)
    merged = a.merge(b, on="key", how="outer", suffixes=("_o", "_r"),
                     indicator=True)
    only = int((merged["_merge"] != "both").sum())
    both = merged[merged["_merge"] == "both"]
    dc = (both["c_o"] - both["c_r"]).abs()
    ds = (both["ss_o"] - both["ss_r"]).abs()
    val_mismatch = int(((dc != 0) | (ds != 0)).sum())
    return {
        "n_keys_orig": int(len(a)),
        "n_keys_rep": int(len(b)),
        "n_keys": int(len(a)) if len(a) == len(b) else None,
        "n_mismatch": only + val_mismatch,
        "n_keys_only_one_side": only,
        "n_value_mismatch": val_mismatch,
        "max_abs_diff_c": int(dc.max()) if len(both) else None,
        "max_abs_diff_ss": int(ds.max()) if len(both) else None,
    }


def main():
    os.makedirs(OUTDIR, exist_ok=True)
    run_started = datetime.now(timezone.utc).isoformat()
    instances = []
    plan = []
    for fam in FAMILIES:
        for seed in SEEDS:
            plan.append((f"outeq_1m_{fam}_s{seed}", "EQ1M", 1_000_000,
                         EQ1M_PIPELINES))
            plan.append((f"outeq_200k_{fam}_s{seed}", "EQ200K", 200_000,
                         EQ200K_PIPELINES))

    tmpdir = tempfile.mkdtemp(prefix="outeq_")
    for tag, scale, n_fact, pipes in plan:
        corpus_dir = os.path.join(DATA, tag)
        with open(os.path.join(corpus_dir, "validation.json")) as f:
            val = json.load(f)
        assert val["all_exact"] is True, f"{tag}: validation not all_exact"
        for pid, col, kind in pipes:
            gt_v, gt_load = gt_verdict_at_check_scale(corpus_dir, pid, n_fact)
            orig_sql, rep_sql = sql_pair(kind, col)
            rec = {"dataset": tag, "scale": scale, "pipeline": pid,
                   "key_col": col, "fix_kind": kind,
                   "gt_verdict_at_check_scale": gt_v,
                   "gt_load_at_check_scale": gt_load,
                   "sql_orig": orig_sql, "sql_rep": rep_sql}
            op = os.path.join(tmpdir, f"{tag}_{pid}_orig.parquet")
            rp = os.path.join(tmpdir, f"{tag}_{pid}_rep.parquet")
            st_o, wall_o, why_o = run_one_query(corpus_dir, orig_sql, op)
            rec["wall_orig_s"] = round(wall_o, 3)
            if st_o != "OK":
                rec.update(status="INFEASIBLE", infeasible_side="orig",
                           infeasible_reason=why_o, wall_rep_s=None,
                           n_keys=None, n_mismatch=None,
                           max_abs_diff_c=None, max_abs_diff_ss=None)
                instances.append(rec)
                print(f"{tag} {pid}: INFEASIBLE (orig) {why_o}", flush=True)
                continue
            st_r, wall_r, why_r = run_one_query(corpus_dir, rep_sql, rp)
            rec["wall_rep_s"] = round(wall_r, 3)
            if st_r != "OK":
                rec.update(status="INFEASIBLE", infeasible_side="rep",
                           infeasible_reason=why_r,
                           n_keys=None, n_mismatch=None,
                           max_abs_diff_c=None, max_abs_diff_ss=None)
                instances.append(rec)
                print(f"{tag} {pid}: INFEASIBLE (rep) {why_r}", flush=True)
                continue
            cmp_res = compare(op, rp)
            rec.update(cmp_res)
            rec["status"] = "EQUAL" if cmp_res["n_mismatch"] == 0 else "MISMATCH"
            instances.append(rec)
            print(f"{tag} {pid}: {rec['status']} n_keys={cmp_res['n_keys']} "
                  f"n_mismatch={cmp_res['n_mismatch']} "
                  f"wall=({wall_o:.2f}s,{wall_r:.2f}s) gt={gt_v}", flush=True)

    # pooled tallies
    def tally(recs):
        return {"checked": len(recs),
                "EQUAL": sum(1 for r in recs if r["status"] == "EQUAL"),
                "MISMATCH": sum(1 for r in recs if r["status"] == "MISMATCH"),
                "INFEASIBLE": sum(1 for r in recs if r["status"] == "INFEASIBLE")}

    pooled = tally(instances)
    per_pipeline = {}
    for pid in ("G_A", "G_N", "W_A", "J_A", "J_B", "J_N", "F_A", "F_B"):
        per_pipeline[pid] = tally([r for r in instances if r["pipeline"] == pid])
    per_scale = {s: tally([r for r in instances if r["scale"] == s])
                 for s in ("EQ1M", "EQ200K")}
    gt_dist = {}
    for r in instances:
        gt_dist[r["gt_verdict_at_check_scale"]] = \
            gt_dist.get(r["gt_verdict_at_check_scale"], 0) + 1

    summary = {
        "study": "output-equivalence execution of the feedback fixes",
        "preregistration": "Amendment 5 Section A5.3 (locked 2026-11-06 12:15 UTC)",
        "run_started_utc": run_started,
        "run_finished_utc": datetime.now(timezone.utc).isoformat(),
        "envelope": {"duckdb_threads": 2, "memory_limit": "2GB",
                     "per_query_wall_cap_s": TIMEOUT_S,
                     "timeout_method": "one subprocess per (dataset, pipeline, side) "
                                       "query (code/outeq_runner.py); driver "
                                       "subprocess timeout kills on exceed; not retried"},
        "corpus_validation": "all 12 corpora validation.json all_exact=true "
                             "(asserted by this driver before checking)",
        "pooled": pooled,
        "per_pipeline": per_pipeline,
        "per_scale": per_scale,
        "gt_verdict_at_check_scale_distribution": gt_dist,
        "instances": instances,
    }
    with open(os.path.join(OUTDIR, "summary.json"), "w") as f:
        json.dump(summary, f, indent=1)
    write_readme(summary)
    print(json.dumps({"pooled": pooled, "per_pipeline": per_pipeline,
                      "per_scale": per_scale, "gt_dist": gt_dist}, indent=1))


